_state_db: sqlite3.Connection | None = None


def _get_state_db() -> sqlite3.Connection:
    """Return engagement state DB with reporting schema tables ensured."""
    global _state_db
    if _state_db is not None:
        return _state_db
    db_path = resolve_state_db_path()
    try:
        _state_db = sqlite3.connect(db_path, check_same_thread=False)
    except sqlite3.Error as exc:
        raise StateDBError(f"Cannot open state database at {db_path}: {exc}") from exc
    _state_db.row_factory = sqlite3.Row
    _state_db.execute("PRAGMA journal_mode=WAL")
    _state_db.executescript(_STATE_SCHEMA)
    _state_db.commit()
    _get_attack_db()
    return _state_db


def _row_dict(row: sqlite3.Row | None) -> dict[str, Any]:
    if row is None:
        return {}
    return dict(row)


def _parse_ts(value: str) -> datetime | None:
    if not value:
        return None
    raw = value.strip()
    for fmt in (
        "%Y-%m-%d %H:%M:%S",
        "%Y-%m-%d %H:%M:%S UTC",
        "%Y-%m-%dT%H:%M:%S",
        "%Y-%m-%dT%H:%M:%SZ",
    ):
        try:
            dt = datetime.strptime(raw.replace(" UTC", ""), fmt.replace(" UTC", "").replace("Z", ""))
            if dt.tzinfo is None:
                return dt.replace(tzinfo=timezone.utc)
            return dt
        except ValueError:
            continue
    try:
        dt = datetime.fromisoformat(raw.replace("Z", "+00:00"))
        if dt.tzinfo is None:
            return dt.replace(tzinfo=timezone.utc)
        return dt
    except ValueError:
        return None


def _redact_credential(row: dict[str, Any]) -> dict[str, Any]:
    out = dict(row)
    if "secret" in out:
        out["secret"] = REDACTED_SECRET
    return out


def _hostname_for_target(db: sqlite3.Connection, target_id: int | None) -> str:
    if not target_id:
        return ""
    row = db.execute("SELECT hostname FROM targets WHERE id = ?", (target_id,)).fetchone()
    return row["hostname"] if row else ""


def _fetch_targets(db: sqlite3.Connection) -> list[dict[str, Any]]:
    return [_row_dict(r) for r in db.execute("SELECT * FROM targets ORDER BY id").fetchall()]


def _fetch_credentials(db: sqlite3.Connection) -> list[dict[str, Any]]:
    rows = db.execute(
        """
        SELECT c.*, t.hostname AS target_hostname
        FROM credentials c
        LEFT JOIN targets t ON c.target_id = t.id
        ORDER BY c.id
        """
    ).fetchall()
    return [_redact_credential(_row_dict(r)) for r in rows]


def _fetch_findings(db: sqlite3.Connection) -> list[dict[str, Any]]:
    rows = db.execute(
        """
        SELECT f.*, t.hostname AS target_hostname
        FROM findings f
        LEFT JOIN targets t ON f.target_id = t.id
        ORDER BY f.id
        """
    ).fetchall()
    return [_row_dict(r) for r in rows]


def _fetch_pivot_paths(db: sqlite3.Connection) -> list[dict[str, Any]]:
    rows = db.execute(
        """
        SELECT p.*,
               s.hostname AS source_hostname,
               d.hostname AS dest_hostname
        FROM pivot_paths p
        LEFT JOIN targets s ON p.source_target_id = s.id
        LEFT JOIN targets d ON p.dest_target_id = d.id
        ORDER BY p.id
        """
    ).fetchall()
    return [_row_dict(r) for r in rows]


def _fetch_attack_techniques(db: sqlite3.Connection) -> list[dict[str, Any]]:
    try:
        rows = db.execute(
            "SELECT * FROM attack_techniques ORDER BY timestamp, id"
        ).fetchall()
    except sqlite3.Error:
        return []
    return [_row_dict(r) for r in rows]


def _group_techniques_by_tactic(
    techniques: list[dict[str, Any]],
) -> dict[str, list[dict[str, Any]]]:
    by_tactic: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for rec in techniques:
        tactic = rec.get("tactic") or "Unknown"
        by_tactic[tactic].append(rec)
    return dict(by_tactic)


def _build_timeline_entries(
    db: sqlite3.Connection,
    *,
    session_id: str = "",
    hours: int | None = None,
) -> list[dict[str, Any]]:
    entries: list[dict[str, Any]] = []
    cutoff: datetime | None = None
    if hours is not None and hours > 0:
        cutoff = datetime.now(timezone.utc) - timedelta(hours=hours)

    filter_session = session_id.strip() if session_id else ""

    for row in _fetch_attack_techniques(db):
        if filter_session and row.get("session_id") != filter_session:
            continue
        ts = row.get("timestamp", "")
        if cutoff and (_parse_ts(ts) or datetime.min.replace(tzinfo=timezone.utc)) < cutoff:
            continue
        tid = row.get("technique_id", "")
        entries.append({
            "timestamp": ts,
            "tool_name": row.get("tool_name", ""),
            "session_id": row.get("session_id", ""),
            "outcome": row.get("outcome", TechniqueOutcome.UNKNOWN.value),
            "attack_technique_ids": [tid] if tid else [],
            "summary": f"{row.get('name', '')} ({tid})".strip(),
            "target_hostname": _hostname_for_target(db, row.get("target_id")),
            "source": "attack_techniques",
        })

    for row in db.execute(
        """
        SELECT a.*, t.hostname AS target_hostname
        FROM access_log a
        LEFT JOIN targets t ON a.target_id = t.id
        ORDER BY a.timestamp, a.id
        """
    ).fetchall():
        rec = _row_dict(row)
        if filter_session and rec.get("session_id") != filter_session:
            continue
        ts = rec.get("timestamp", "")
        if cutoff and (_parse_ts(ts) or datetime.min.replace(tzinfo=timezone.utc)) < cutoff:
            continue
        method = rec.get("method", "")
        technique_ids = [
            m.technique_id for m in get_techniques_for_tool(method)
        ] if method.startswith("sliver_") else []
        entries.append({
            "timestamp": ts,
            "tool_name": method or "access_log",
            "session_id": rec.get("session_id", ""),
            "outcome": ActionOutcome.OK.value if rec.get("status") == "active" else rec.get("status", "ok"),
            "attack_technique_ids": technique_ids,
            "summary": f"Access event: {method} ({rec.get('status', '')})",
            "target_hostname": rec.get("target_hostname", ""),
            "source": "access_log",
        })

    try:
        for row in db.execute(
            """
            SELECT e.*, t.hostname AS target_hostname
            FROM engagement_actions e
            LEFT JOIN targets t ON e.target_id = t.id
            ORDER BY e.timestamp, e.id
            """
        ).fetchall():
            rec = _row_dict(row)
            if filter_session and rec.get("session_id") != filter_session:
                continue
            ts = rec.get("timestamp", "")
            if cutoff and (_parse_ts(ts) or datetime.min.replace(tzinfo=timezone.utc)) < cutoff:
                continue
            try:
                technique_ids = json.loads(rec.get("attack_technique_ids") or "[]")
            except json.JSONDecodeError:
                technique_ids = []
            entries.append({
                "timestamp": ts,
                "tool_name": rec.get("tool_name", ""),
                "session_id": rec.get("session_id", ""),
                "outcome": rec.get("outcome", ActionOutcome.OK.value),
                "attack_technique_ids": technique_ids,
                "summary": rec.get("summary", ""),
                "target_hostname": rec.get("target_hostname", ""),
                "source": "engagement_actions",
            })
    except sqlite3.Error:
        pass

    entries.sort(key=lambda e: (_parse_ts(e.get("timestamp", "")) or datetime.min.replace(tzinfo=timezone.utc), e.get("tool_name", "")))
    return entries


def _engagement_duration(db: sqlite3.Connection) -> dict[str, Any]:
    meta_row = None
    try:
        meta_row = db.execute(
            "SELECT value FROM engagement_meta WHERE key = 'started_at'"
        ).fetchone()
    except sqlite3.Error:
        pass
    started = meta_row["value"] if meta_row else ""
    if not started:
        ts_rows: list[str] = []
        for rec in _fetch_attack_techniques(db):
            if rec.get("timestamp"):
                ts_rows.append(rec["timestamp"])
        for row in db.execute("SELECT timestamp FROM access_log ORDER BY timestamp LIMIT 1").fetchall():
            ts_rows.append(row["timestamp"])
        if ts_rows:
            ts_rows.sort()
            started = ts_rows[0]
    ended = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    duration_hours: float | None = None
    start_dt = _parse_ts(started) if started else None
    end_dt = _parse_ts(ended)
    if start_dt and end_dt:
        duration_hours = round((end_dt - start_dt).total_seconds() / 3600, 2)
    return {
        "started_at": started or "unknown",
        "ended_at": ended,
        "duration_hours": duration_hours,
    }


def _build_coverage_section(db: sqlite3.Connection) -> dict[str, Any]:
    registry_index = _build_registry_index()
    exercised, attempted_failed, _ = _query_technique_sets(db, "")
    tactic_sections: dict[str, Any] = {}
    total_available = 0
    total_exercised = 0
    for tactic in sorted(registry_index.keys()):
        available_ids = sorted(registry_index[tactic].keys())
        exercised_ids = sorted(set(available_ids) & exercised)
        gap_ids = sorted(set(available_ids) - set(exercised_ids))
        total_available += len(available_ids)
        total_exercised += len(exercised_ids)
        tactic_sections[tactic] = {
            "exercised": exercised_ids,
            "gap": gap_ids,
            "attempted_failed": sorted(set(available_ids) & attempted_failed),
        }
    pct = (total_exercised / total_available * 100.0) if total_available else 0.0
    return {
        "by_tactic": tactic_sections,
        "summary": {
            "total_available": total_available,
            "total_exercised": total_exercised,
            "coverage_percent": round(pct, 2),
        },
    }


def _findings_by_severity(findings: list[dict[str, Any]]) -> dict[str, list[dict[str, Any]]]:
    grouped: dict[str, list[dict[str, Any]]] = {s: [] for s in SEVERITY_ORDER}
    for f in findings:
        sev = (f.get("severity") or "info").lower()
        if sev not in grouped:
            grouped[sev] = []
        grouped[sev].append(f)
    return grouped


def _build_recommendations(
    db: sqlite3.Connection,
    findings: list[dict[str, Any]],
    coverage: dict[str, Any],
) -> list[str]:
    recs: list[str] = []
    critical = [f for f in findings if (f.get("severity") or "").lower() == FindingSeverity.CRITICAL.value]
    high = [f for f in findings if (f.get("severity") or "").lower() == FindingSeverity.HIGH.value]
    if critical:
        recs.append(
            f"Address {len(critical)} critical finding(s) before expanding scope."
        )
    if high:
        recs.append(f"Review {len(high)} high-severity finding(s) for immediate risk reduction.")
    pct = coverage.get("summary", {}).get("coverage_percent", 0)
    if pct < 20:
        recs.append(
            "ATT&CK coverage is below 20% — run sliver_attack_coverage and exercise highest-gap tactics."
        )
    for tactic, data in coverage.get("by_tactic", {}).items():
        if data.get("gap") and not data.get("exercised"):
            recs.append(f"No techniques exercised in {tactic} — consider mapped discovery tools.")
            break
    pivot_count = db.execute("SELECT COUNT(*) AS c FROM pivot_paths").fetchone()["c"]
    if pivot_count == 0:
        recs.append("Document lateral movement paths with sliver_state_add_pivot as pivots are validated.")
    if not recs:
        recs.append("Continue structured enumeration and document new findings in the state database.")
    return recs


def _build_report_payload(db: sqlite3.Connection) -> dict[str, Any]:
    targets = _fetch_targets(db)
    credentials = _fetch_credentials(db)
    findings = _fetch_findings(db)
    pivots = _fetch_pivot_paths(db)
    techniques = _fetch_attack_techniques(db)
    timeline = _build_timeline_entries(db)
    coverage = _build_coverage_section(db)
    duration = _engagement_duration(db)
    findings_grouped = _findings_by_severity(findings)

    severity_counts = {s: len(findings_grouped.get(s, [])) for s in SEVERITY_ORDER}
    key_findings_count = severity_counts.get("critical", 0) + severity_counts.get("high", 0)

    services_by_target: dict[int, list[dict[str, Any]]] = defaultdict(list)
    try:
        for row in db.execute("SELECT * FROM target_services ORDER BY target_id, port").fetchall():
            rec = _row_dict(row)
            services_by_target[rec["target_id"]].append(rec)
    except sqlite3.Error:
        pass

    attack_surface = []
    for t in targets:
        tid = t.get("id")
        attack_surface.append({
            **t,
            "services": services_by_target.get(tid, []) if tid else [],
        })

    return {
        "watermark": REPORT_WATERMARK,
        "executive_summary": {
            "engagement": duration,
            "scope": {
                "targets": len(targets),
                "credentials": len(credentials),
                "pivot_paths": len(pivots),
                "timeline_events": len(timeline),
            },
            "key_findings_count": key_findings_count,
            "findings_by_severity": severity_counts,
        },
        "timeline": timeline,
        "mitre_attack_coverage": {
            "techniques_exercised_by_tactic": _group_techniques_by_tactic(techniques),
            "matrix": coverage,
        },
        "targets": targets,
        "credentials": credentials,
        "findings_by_severity": findings_grouped,
        "pivot_paths": pivots,
        "attack_surface": attack_surface,
        "recommendations": _build_recommendations(db, findings, coverage),
    }


def _report_to_markdown(payload: dict[str, Any]) -> str:
    lines: list[str] = []
    es = payload.get("executive_summary", {})
    eng = es.get("engagement", {})
    scope = es.get("scope", {})

    lines.append("# Engagement Report")
    lines.append("")
    lines.append(f"*{payload.get('watermark', REPORT_WATERMARK)}*")
    lines.append("")

    lines.append("## Executive Summary")
    lines.append(f"- **Duration:** {eng.get('started_at', 'unknown')} → {eng.get('ended_at', 'now')}")
    if eng.get("duration_hours") is not None:
        lines.append(f"- **Elapsed (hours):** {eng['duration_hours']}")
    lines.append(f"- **Targets:** {scope.get('targets', 0)}")
    lines.append(f"- **Credentials (count):** {scope.get('credentials', 0)}")
    lines.append(f"- **Key findings (critical + high):** {es.get('key_findings_count', 0)}")
    lines.append("")

    lines.append("## Timeline")
    timeline = payload.get("timeline", [])
    if not timeline:
        lines.append("_No timeline events recorded._")
    else:
        for entry in timeline[:500]:
            tags = ", ".join(entry.get("attack_technique_ids") or []) or "—"
            lines.append(
                f"- `{entry.get('timestamp', '')}` **{entry.get('tool_name', '')}** "
                f"({entry.get('outcome', '')}) — {entry.get('summary', '')} [{tags}]"
            )
        if len(timeline) > 500:
            lines.append(f"\n_… truncated ({len(timeline) - 500} additional events)._")
    lines.append("")

    lines.append("## MITRE ATT&CK Coverage")
    matrix = payload.get("mitre_attack_coverage", {}).get("matrix", {})
    summary = matrix.get("summary", {})
    lines.append(
        f"- **Coverage:** {summary.get('total_exercised', 0)} / "
        f"{summary.get('total_available', 0)} techniques "
        f"({summary.get('coverage_percent', 0)}%)"
    )
    for tactic, data in sorted(matrix.get("by_tactic", {}).items()):
        exercised = ", ".join(data.get("exercised", [])) or "none"
        lines.append(f"- **{tactic}:** {exercised}")
    lines.append("")

    lines.append("## Targets")
    for t in payload.get("targets", []):
        lines.append(
            f"- **{t.get('hostname', '?')}** ({t.get('ip', '')}) — "
            f"access: {t.get('access_level', 'unknown')}, OS: {t.get('os', '')}"
        )
    if not payload.get("targets"):
        lines.append("_No targets recorded._")
    lines.append("")

    lines.append("## Credentials")
    for c in payload.get("credentials", []):
        lines.append(
            f"- **{c.get('username', '?')}** @ {c.get('domain', '')} "
            f"({c.get('cred_type', '')}) secret: {REDACTED_SECRET}"
        )
    if not payload.get("credentials"):
        lines.append("_No credentials logged._")
    lines.append("")

    lines.append("## Findings by Severity")
    for sev in SEVERITY_ORDER:
        items = payload.get("findings_by_severity", {}).get(sev, [])
        if not items:
            continue
        lines.append(f"### {sev.title()}")
        for f in items:
            lines.append(f"- **{f.get('title', '')}:** {f.get('description', '')}")
    lines.append("")

    lines.append("## Pivot Paths")
    for p in payload.get("pivot_paths", []):
        lines.append(
            f"- {p.get('source_hostname', '?')} → {p.get('dest_hostname', '?')} "
            f"via {p.get('method', '')} ({p.get('status', '')})"
        )
    if not payload.get("pivot_paths"):
        lines.append("_No pivot paths recorded._")
    lines.append("")

    lines.append("## Recommendations")
    for r in payload.get("recommendations", []):
        lines.append(f"- {r}")
    lines.append("")

    return "\n".join(lines)


def _success_response(data: dict[str, Any]) -> str:
    return json.dumps(ToolResponse(status=ToolStatus.SUCCESS, data=data).to_json(), indent=2, default=str)


def _error_response(tool: str, exc: Exception) -> str:
    if isinstance(exc, ValidationError):
        resp = ToolResponse(
            status=ToolStatus.ERROR,
            error=str(exc),
            error_type="ValidationError",
            hints=getattr(exc, "hints", []),
        )
        return json.dumps(resp.to_json(), indent=2)
    if isinstance(exc, StateDBError):
        resp = ToolResponse(
            status=ToolStatus.ERROR,
            error=str(exc),
            error_type="StateDBError",
            hints=exc.hints,
        )
        return json.dumps(resp.to_json(), indent=2)
    from server import _format_tool_error  # noqa: PLC0415

    return _format_tool_error(tool, exc)


async def sliver_generate_report(format: str = "markdown") -> str:
    """Generate a structured engagement report from state DB data.

    Queries targets, credentials, findings, access log, attack techniques,
    and pivot paths. Credential secrets are always redacted in output.

    Args:
        format: Output format — ``markdown`` (default) or ``json``.
    """
    tool = "sliver_generate_report"
    try:
        fmt = (format or "markdown").strip().lower()
        if fmt not in ("markdown", "json"):
            raise ValidationError("format", format, 'must be "markdown" or "json"')

        db = _get_state_db()
        payload = _build_report_payload(db)

        if fmt == "json":
            return _success_response({"report": payload, "format": "json"})

        markdown = _report_to_markdown(payload)
        return _success_response({"report": markdown, "format": "markdown"})

    except (ValidationError, StateDBError) as exc:
        return _error_response(tool, exc)
    except Exception as exc:
        logger.exception("Report generation failed")
        return _error_response(tool, exc)


async def sliver_engagement_timeline(session_id: str = "", hours: int = 24) -> str:
    """Return a chronological engagement action log with ATT&CK technique tags.

    Merges ``attack_techniques``, ``access_log``, and ``engagement_actions``
    tables. Filters by session and rolling time window.

    Args:
        session_id: Optional session ID filter (empty = all sessions).
        hours: Include events from the last N hours (default 24). Use 0 for all time.
    """
    tool = "sliver_engagement_timeline"
    try:
        filter_session = ""
        if session_id and session_id.strip():
            filter_session = validate_session_id(session_id.strip())

        if hours < 0:
            raise ValidationError("hours", str(hours), "must be >= 0")

        db = _get_state_db()
        window = None if hours == 0 else hours
        entries = _build_timeline_entries(db, session_id=filter_session, hours=window)

        return _success_response({
            "entries": entries,
            "count": len(entries),
            "session_filter": filter_session or None,
            "hours": hours if hours != 0 else None,
        })

    except (ValidationError, StateDBError) as exc:
        return _error_response(tool, exc)
    except Exception as exc:
        logger.exception("Timeline query failed")
        return _error_response(tool, exc)
