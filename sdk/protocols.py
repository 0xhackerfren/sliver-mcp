"""SDK constraint surface: abstract protocols.

These protocols define the interfaces that tool modules depend on.
Implementations live in sliver_mcp/; tests can substitute mocks
that satisfy these protocols without connecting to a real teamserver.
"""

from __future__ import annotations

from typing import Any, Protocol, runtime_checkable

from .types import (
    AccessLog,
    AttackTechniqueRecord,
    Credential,
    Finding,
    OpsecScanResult,
    PivotPath,
    SessionInfo,
    Target,
    TargetService,
    ToolResponse,
)


@runtime_checkable
class C2Client(Protocol):
    """Abstract interface over the Sliver gRPC client."""

    async def connect(self) -> None: ...
    async def disconnect(self) -> None: ...
    async def version(self) -> str: ...
    async def is_connected(self) -> bool: ...

    async def sessions(self) -> list[SessionInfo]: ...
    async def beacons(self) -> list[SessionInfo]: ...
    async def interact_session(self, session_id: str) -> Any: ...
    async def interact_beacon(self, beacon_id: str) -> Any: ...
    async def kill_session(self, session_id: str) -> None: ...
    async def kill_beacon(self, beacon_id: str) -> None: ...

    async def jobs(self) -> list[dict[str, Any]]: ...
    async def start_https_listener(self, host: str, port: int, **kwargs: Any) -> Any: ...
    async def start_http_listener(self, host: str, port: int, **kwargs: Any) -> Any: ...
    async def start_dns_listener(self, domains: list[str], **kwargs: Any) -> Any: ...
    async def start_mtls_listener(self, host: str, port: int, **kwargs: Any) -> Any: ...
    async def start_tcp_listener(self, host: str, port: int, **kwargs: Any) -> Any: ...
    async def start_wg_listener(self, host: str, port: int, **kwargs: Any) -> Any: ...
    async def kill_job(self, job_id: int) -> None: ...

    async def generate(self, **kwargs: Any) -> Any: ...
    async def regenerate_implant(self, name: str) -> bytes: ...
    async def implant_builds(self) -> list[dict[str, Any]]: ...

    async def operators(self) -> list[dict[str, Any]]: ...


@runtime_checkable
class StateStore(Protocol):
    """Abstract interface over the engagement SQLite state database."""

    def add_target(self, target: Target) -> int: ...
    def get_targets(self) -> list[Target]: ...
    def get_target_by_ip(self, ip: str) -> Target | None: ...

    def add_credential(self, cred: Credential) -> int: ...
    def get_credentials(self, target_id: int | None = None) -> list[Credential]: ...

    def add_finding(self, finding: Finding) -> int: ...
    def get_findings(self, severity: str | None = None) -> list[Finding]: ...

    def log_access(self, log: AccessLog) -> int: ...
    def get_access_log(self, session_id: str | None = None) -> list[AccessLog]: ...

    def add_pivot(self, pivot: PivotPath) -> int: ...
    def get_pivots(self) -> list[PivotPath]: ...

    def add_technique(self, record: AttackTechniqueRecord) -> int: ...
    def get_techniques(self, tactic: str | None = None) -> list[AttackTechniqueRecord]: ...

    def add_service(self, service: TargetService) -> int: ...
    def get_services(self, target_id: int | None = None) -> list[TargetService]: ...

    def get_summary(self) -> dict[str, Any]: ...
    def export_all(self) -> dict[str, Any]: ...


@runtime_checkable
class OpsecGuard(Protocol):
    """Abstract interface for OPSEC pre-flight checks."""

    async def scan_session(self, session_id: str) -> OpsecScanResult: ...
    async def preflight(self, session_id: str, tool_name: str) -> OpsecScanResult: ...
    def is_high_risk(self, tool_name: str) -> bool: ...
    def get_mode(self) -> str: ...  # "warn", "block", "silent"
